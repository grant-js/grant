#!/usr/bin/env node
/**
 * Insert stable operationIds into REST OpenAPI registrations and write a compact
 * operations list for @grantjs/cli. No workspace package import — file copy only.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const openapiDir = join(root, 'apps/api/src/rest/openapi');
const operationsOut = join(root, 'packages/@grantjs/cli/src/spec/operations.ts');

function kebabToPascal(seg) {
  return seg
    .split(/[-_]/)
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('');
}

function operationId(method, path) {
  const parts = path
    .replace(/^\//, '')
    .split('/')
    .filter(Boolean)
    .flatMap((seg) => {
      if (seg.startsWith('{') && seg.endsWith('}')) {
        return ['By', kebabToPascal(seg.slice(1, -1))];
      }
      return [kebabToPascal(seg)];
    });
  return method.toLowerCase() + parts.join('');
}

function pathParams(path) {
  return [...path.matchAll(/\{([^}]+)\}/g)].map((match) => match[1]);
}

function extractTags(block) {
  const match = block.match(/tags:\s*\[([^\]]*)\]/);
  if (!match) return [];
  return [...match[1].matchAll(/'([^']+)'/g)].map((m) => m[1]);
}

function extractSummary(block) {
  const match = block.match(/summary:\s*'([^']*)'/);
  return match?.[1] ?? '';
}

function insertOperationIds(source) {
  const lines = source.split('\n');
  const out = [];
  for (let i = 0; i < lines.length; i++) {
    out.push(lines[i]);
    const methodMatch = lines[i].match(/^\s*method:\s*'(\w+)',\s*$/);
    const pathMatch = lines[i + 1]?.match(/^\s*path:\s*'([^']+)',\s*$/);
    if (!methodMatch || !pathMatch) continue;
    const next = lines[i + 2] ?? '';
    if (next.includes('operationId:')) continue;
    const id = operationId(methodMatch[1], pathMatch[1]);
    const indent = lines[i].match(/^\s*/)[0];
    out.push(lines[i + 1]);
    out.push(`${indent}operationId: '${id}',`);
    i += 1;
  }
  return out.join('\n');
}

function extractOperations(source) {
  const operations = [];
  const re =
    /registry\.registerPath\(\{\s*method:\s*'(\w+)',\s*path:\s*'([^']+)',\s*operationId:\s*'([^']+)',([\s\S]*?)\n {2}\}\);/g;
  let match;
  while ((match = re.exec(source))) {
    const [, method, path, id, rest] = match;
    operations.push({
      operationId: id,
      method,
      path,
      tags: extractTags(rest),
      summary: extractSummary(rest),
      pathParams: pathParams(path),
    });
  }
  return operations;
}

const files = readdirSync(openapiDir)
  .filter((name) => name.endsWith('.openapi.ts') && name !== 'config.openapi.ts')
  .sort();

const all = [];
for (const name of files) {
  const filePath = join(openapiDir, name);
  const original = readFileSync(filePath, 'utf-8');
  const updated = insertOperationIds(original);
  if (updated !== original) {
    writeFileSync(filePath, updated);
  }
  all.push(...extractOperations(readFileSync(filePath, 'utf-8')));
}

all.sort((a, b) => a.operationId.localeCompare(b.operationId));

const body = `import type { CliOperation } from './types.js';

/** Generated by scripts/vendor-cli-openapi.mjs — do not edit by hand. */
export const vendoredOperations: CliOperation[] = ${JSON.stringify(all, null, 2)};
`;

writeFileSync(operationsOut, body);
console.log(`Wrote ${all.length} operations to ${operationsOut}`);
